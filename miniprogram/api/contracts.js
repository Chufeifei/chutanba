function normalizeReservationStates(source = {}) {
  const raw = source.reservationStatus || source.status;
  let reservationStatus = LEGACY_RESERVATION_STATUS[raw];
  if (!reservationStatus) {
    reservationStatus = Object.values(RESERVATION_STATUS).includes(raw)
      ? raw
      : RESERVATION_STATUS.EXPIRED;
  }
  let benefitRedemptionStatus = source.benefitRedemptionStatus;
  if (!Object.values(BENEFIT_REDEMPTION_STATUS).includes(benefitRedemptionStatus)) {
    if (!source.benefitSnapshot && !source.benefit_snapshot) benefitRedemptionStatus = BENEFIT_REDEMPTION_STATUS.NOT_APPLICABLE;
    else if (source.status === 'CHECKED_IN') benefitRedemptionStatus = BENEFIT_REDEMPTION_STATUS.REDEEMED;
    else benefitRedemptionStatus = reservationStatus === RESERVATION_STATUS.ACTIVE
      ? BENEFIT_REDEMPTION_STATUS.AVAILABLE : BENEFIT_REDEMPTION_STATUS.VOID;
  }
  return { ...source, reservationStatus, benefitRedemptionStatus };
}

function isSixDigitBenefitCode(value) { return /^\d{6}$/.test(String(value || '')); }

